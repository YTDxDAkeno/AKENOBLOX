#
#   embed.py <input> <output.c> <symbol>
#
# Writes `const unsigned char <symbol>[]` and `const unsigned long
# <symbol>_size`, with the input's SHA-256 in a comment so a build log ties the
# embedded bytes to the file they came from.
import hashlib
import pathlib
import re
import sys


def main() -> int:
    if len(sys.argv) != 4:
        print("usage: embed.py <input> <output.c> <symbol>", file=sys.stderr)
        return 2
    source, output, symbol = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3]
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", symbol):
        print(f"embed.py: {symbol!r} is not a C identifier", file=sys.stderr)
        return 2
    data = source.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    lines = [
        "/* Generated by tools/build/embed.py; do not edit. */",
        f"/* {source.name}: {len(data)} bytes, sha256 {digest} */",
        "#include <stddef.h>",
        f"const unsigned char {symbol}[{max(len(data), 1)}] __attribute__((aligned(16))) = {{",
    ]
    for i in range(0, len(data), 16):
        lines.append("   " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append(f"const size_t {symbol}_size = {len(data)};")
    lines.append(f'const char {symbol}_sha256[] = "{digest}";')
    output.parent.mkdir(parents=True, exist_ok=True)
    tmp = output.with_suffix(output.suffix + ".tmp")
    tmp.write_text("\n".join(lines) + "\n")
    tmp.replace(output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
